/**
 * Keep large test fixtures out of Git, and put the same bytes back before tests run.
 *
 * Most fixtures are small JSON or binary files and stay in Git. A fixture larger than {@link limit} is a
 * download instead: `tests/fixtures/store.json` records its path, size and SHA-256, and the bytes live as an
 * asset of the repository's `fixtures` GitHub release, named by that SHA-256. Content addressing means two
 * commits that share a fixture share one asset, and a changed fixture is a new asset rather than an edit.
 *
 * ```text
 *   store.json entry ──► .tmp/fixtures/<sha256>  (download cache, verified)
 *                    └─► tests/fixtures/<path>   (copy the tests import, ignored by Git)
 * ```
 *
 * Three commands own the workflow:
 *
 * - `fetch` downloads every listed file that is missing or wrong, verifies its size and SHA-256, and writes it
 *   in place. Tests and type checks depend on it. It never trusts a cached file without hashing it.
 * - `write` moves every tracked fixture over the limit into the manifest and regenerates the ignore list. Run
 *   it after adding a large fixture; then upload the new assets (see `docs/fixtures.md`).
 * - `check` fails when a tracked fixture is over the limit, when the manifest is malformed, or when the
 *   generated ignore list is stale. It reads no network.
 *
 * @module
 */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

/** Fixtures above this many bytes leave Git. 256 KiB keeps ordinary JSON vectors reviewable in a diff. */
export const limit = 256 * 1024;

/** Where the release assets live. A fork can point this at its own copy. */
export const origin = process.env.OPFS_FIXTURES_URL ?? "https://github.com/okikio/opfs/releases/download/fixtures";

/** One stored fixture: where tests expect it, and the exact bytes it must have. */
export interface EntryType {
  readonly size: number;
  readonly sha256: string;
}

/** The manifest format. Paths are repository-relative with `/` separators, sorted for stable diffs. */
export interface StoreType {
  readonly version: 1;
  readonly limit: number;
  readonly files: Readonly<Record<string, EntryType>>;
}

const root = fileURLToPath(new URL("../../", import.meta.url));
const manifest = "tests/fixtures/store.json";
const ignore = "tests/fixtures/.gitignore";
const cache = ".tmp/fixtures";

/** Read and validate the manifest. A missing manifest is an empty store, which is valid. */
export async function load(base = root): Promise<StoreType> {
  let text: string;
  try {
    text = await readFile(join(base, manifest), "utf8");
  } catch {
    return { version: 1, limit, files: {} };
  }
  return parse(text);
}

/** Validate manifest text. Every entry needs a fixture path, a positive size and a lowercase SHA-256. */
export function parse(text: string): StoreType {
  const value: unknown = JSON.parse(text);
  const store = value as Partial<StoreType>;
  if (!store || store.version !== 1 || typeof store.files !== "object" || store.files === null) {
    throw new TypeError(`${manifest} must be { "version": 1, "limit": number, "files": { ... } }.`);
  }
  const problems: string[] = [];
  for (const [path, entry] of Object.entries(store.files)) {
    if (!path.startsWith("tests/fixtures/") || path.includes("..") || path.includes("\\")) {
      problems.push(`${path}: the path must stay under tests/fixtures/ and use "/" separators.`);
    }
    if (!Number.isSafeInteger(entry?.size) || entry.size <= 0) {
      problems.push(`${path}: size must be a positive integer.`);
    }
    if (!/^[0-9a-f]{64}$/u.test(entry?.sha256 ?? "")) problems.push(`${path}: sha256 must be 64 lowercase hex digits.`);
  }
  if (problems.length) throw new TypeError(`${manifest} is invalid:\n${problems.join("\n")}`);
  return { version: 1, limit: store.limit ?? limit, files: store.files };
}

/** Serialize with sorted paths and a trailing newline, so `write` is idempotent. */
export function format(files: Readonly<Record<string, EntryType>>): string {
  const sorted = Object.fromEntries(Object.entries(files).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  return `${JSON.stringify({ version: 1, limit, files: sorted }, null, 2)}\n`;
}

/** The generated ignore list: exactly the stored paths, relative to `tests/fixtures/`. */
export function ignored(files: Readonly<Record<string, EntryType>>): string {
  const lines = Object.keys(files).sort().map((path) => `/${path.slice("tests/fixtures/".length)}`);
  return [
    "# Generated by `mise run fixtures -- --write` from store.json. Do not edit by hand.",
    "# These fixtures are downloads; `mise run prepare:fixtures` puts them back.",
    ...lines,
    "",
  ].join("\n");
}

const digest = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");

/** True when the file at `path` has exactly the entry's size and hash. */
async function matches(path: string, entry: EntryType): Promise<boolean> {
  try {
    if ((await stat(path)).size !== entry.size) return false;
    return digest(await readFile(path)) === entry.sha256;
  } catch {
    return false;
  }
}

/**
 * Download every missing or wrong fixture, verify it, and write it in place. Returns how many files it wrote.
 *
 * Downloads land in `.tmp/fixtures/<sha256>` first and are renamed into place only after the hash matches, so
 * an interrupted download never leaves a truncated fixture that a later run would trust. CI caches that
 * directory by the manifest hash; a restored file is still hashed before use.
 */
export async function fetchAll(base = root, request: typeof fetch = fetch): Promise<number> {
  const { files } = await load(base);
  let written = 0;
  for (const [path, entry] of Object.entries(files)) {
    const target = join(base, path);
    if (await matches(target, entry)) continue;
    const stored = join(base, cache, entry.sha256);
    if (!(await matches(stored, entry))) {
      const response = await request(`${origin}/${entry.sha256}`, { redirect: "follow" });
      if (!response.ok) {
        throw new Error(`Fixture ${path} (${entry.sha256}) is not downloadable: HTTP ${response.status}.`);
      }
      const bytes = new Uint8Array(await response.arrayBuffer());
      if (bytes.byteLength !== entry.size || digest(bytes) !== entry.sha256) {
        throw new Error(`Fixture ${path} downloaded with the wrong size or SHA-256; refusing to use it.`);
      }
      await mkdir(dirname(stored), { recursive: true });
      await writeFile(`${stored}.partial`, bytes);
      await rename(`${stored}.partial`, stored);
    }
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, await readFile(stored));
    written += 1;
  }
  return written;
}

/** Tracked fixture paths, from Git's index. */
function tracked(base: string): string[] {
  const out = execFileSync("git", ["-C", base, "ls-files", "-z", "--", "tests/fixtures"], { encoding: "utf8" });
  return out.split("\0").filter(Boolean);
}

/** Problems that `check` reports. Empty means the store and the tree agree. */
export async function audit(base = root): Promise<string[]> {
  const problems: string[] = [];
  let store: StoreType;
  try {
    store = await load(base);
  } catch (error) {
    return [(error as Error).message];
  }
  for (const path of tracked(base)) {
    if (path === manifest || path === ignore) continue;
    const size = (await stat(join(base, path)).catch(() => undefined))?.size ?? 0;
    if (size > limit) problems.push(`${path} is ${size} bytes; fixtures over ${limit} bytes belong in ${manifest}.`);
    if (store.files[path]) problems.push(`${path} is both tracked and listed in ${manifest}.`);
  }
  const expected = Object.keys(store.files).length ? ignored(store.files) : "";
  const actual = await readFile(join(base, ignore), "utf8").catch(() => "");
  if (actual !== expected) problems.push(`${ignore} is stale; run \`mise run fixtures -- --write\`.`);
  return problems;
}

/**
 * Move tracked fixtures over the limit into the manifest, untrack them, and regenerate the ignore list. The
 * bytes stay on disk and in `.tmp/fixtures/`, ready to upload as `fixtures` release assets.
 */
export async function writeStore(base = root): Promise<string[]> {
  const store = await load(base);
  const files: Record<string, EntryType> = { ...store.files };
  const moved: string[] = [];
  for (const path of tracked(base)) {
    if (path === manifest || path === ignore) continue;
    const bytes = await readFile(join(base, path));
    if (bytes.byteLength <= limit) continue;
    const entry = { size: bytes.byteLength, sha256: digest(bytes) };
    files[path] = entry;
    await mkdir(join(base, cache), { recursive: true });
    await writeFile(join(base, cache, entry.sha256), bytes);
    execFileSync("git", ["-C", base, "rm", "--cached", "--quiet", "--", path]);
    moved.push(path);
  }
  // Drop entries whose fixture was deleted from the working tree and is no longer referenced.
  for (const path of Object.keys(files)) {
    const present = await stat(join(base, path)).then(() => true, () => false);
    if (!present && !(await stat(join(base, cache, files[path]!.sha256)).then(() => true, () => false))) {
      delete files[path];
    }
  }
  if (Object.keys(files).length) {
    await writeFile(join(base, manifest), format(files));
    await writeFile(join(base, ignore), ignored(files));
  } else {
    await rm(join(base, manifest), { force: true });
    await rm(join(base, ignore), { force: true });
  }
  return moved;
}

if (import.meta.main) {
  const [command = "check"] = process.argv.slice(2).map((value) => value.replace(/^--/u, ""));
  const base = resolve(process.env.OPFS_ROOT ?? root);
  if (command === "fetch") {
    const count = await fetchAll(base);
    console.log(count ? `Restored ${count} stored fixture(s).` : "All stored fixtures are present.");
  } else if (command === "write") {
    const moved = await writeStore(base);
    console.log(moved.length ? `Moved to ${manifest}:\n${moved.join("\n")}` : "No tracked fixture is over the limit.");
  } else if (command === "check") {
    const problems = await audit(base);
    if (problems.length) {
      console.error(problems.join("\n"));
      process.exitCode = 1;
    } else console.log(`${manifest} and the tracked fixtures agree (limit ${limit} bytes).`);
  } else {
    console.error(`Usage: store.ts fetch | write | check (relative to ${relative(process.cwd(), base) || "."})`);
    process.exitCode = 2;
  }
}
